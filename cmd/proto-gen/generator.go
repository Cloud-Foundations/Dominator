package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/types"
	"maps"
	"regexp"
	"slices"
	"strings"
)

const (
	protoPreamble = `// Code generated by proto-gen. DO NOT EDIT.

syntax = "proto3";

package %s;

`
	protoGoPackage = "option go_package = %q;\n\n"
)

type protoConfig struct {
	GoPackage string // Import path of the generated Go code.
	Package   string // Proto package.
	Service   string // Name of the gRPC service.
}

// wellKnownTypes maps the Go types from other packages which have a proto
// equivalent to it.
var wellKnownTypes = map[string]string{
	"net.HardwareAddr": "string",
	"net.IP":           "string",
	"tags.Tags":        "map<string, string>",
	"time.Duration":    "google.protobuf.Duration",
	"time.Time":        "google.protobuf.Timestamp",
}

var protoImports = map[string]string{
	"google.protobuf.Duration":  "google/protobuf/duration.proto",
	"google.protobuf.Timestamp": "google/protobuf/timestamp.proto",
}

var protoKeyTypes = []string{
	"bool", "int32", "int64", "string", "uint32", "uint64",
}

var (
	identifierPattern = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
	packagePattern    = regexp.MustCompile(
		`^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$`)
)

type typeMapper struct {
	imports  map[string]struct{} // Paths of the proto files to import.
	messages map[string]struct{} // Names of the generated messages.
	named    map[string]string   // Underlying types of non-struct named types.
	visiting map[string]struct{} // Named types being resolved, for recursion.
}

// generateProto returns the text of the .proto file for methods and the
// messages in infos. named is the result of scanNamedTypes. An error is
// returned if config is invalid or a field has a type which a proto message
// cannot express.
func generateProto(config protoConfig, methods []methodInfo, infos []typeInfo,
	named map[string]string) (string, error) {
	if config.GoPackage == "" {
		return "", errors.New("empty Go package")
	}
	if !packagePattern.MatchString(config.Package) {
		return "", fmt.Errorf("invalid proto package name %q", config.Package)
	}
	if !identifierPattern.MatchString(config.Service) {
		return "", fmt.Errorf("invalid service name %q", config.Service)
	}
	if len(infos) < 1 {
		return "", errors.New("no @grpc types to generate")
	}
	messages := make(map[string]struct{}, len(infos))
	for _, info := range infos {
		messages[info.Name] = struct{}{}
	}
	if _, ok := messages[config.Service]; ok && len(methods) > 0 {
		return "", fmt.Errorf("service name %s is also a message name",
			config.Service)
	}
	mapper := newTypeMapper(messages, named)
	var buffer bytes.Buffer
	for i, info := range infos {
		if i > 0 {
			buffer.WriteString("\n")
		}
		fmt.Fprintf(&buffer, "message %s {\n", info.Name)
		for _, field := range info.Fields {
			fieldType, err := mapper.protoTypeOf(field.GoType)
			if err != nil {
				return "", fmt.Errorf("message %s field %s: %w", info.Name,
					field.Name, err)
			}
			fmt.Fprintf(&buffer, "  %s %s = %d;\n", fieldType, field.Name,
				field.Number)
		}
		buffer.WriteString("}\n")
	}
	if len(methods) > 0 {
		buffer.WriteString("\n")
		fmt.Fprintf(&buffer, "service %s {\n", config.Service)
		seen := make(map[string]struct{}, len(methods))
		for _, method := range methods {
			if _, ok := seen[method.Name]; ok {
				return "", fmt.Errorf("duplicate method %s", method.Name)
			}
			seen[method.Name] = struct{}{}
			fmt.Fprintf(&buffer, "  rpc %s(%s) returns (%s);\n", method.Name,
				method.RequestType, method.ResponseType)
		}
		buffer.WriteString("}\n")
	}
	var header bytes.Buffer
	fmt.Fprintf(&header, protoPreamble, config.Package)
	for _, path := range slices.Sorted(maps.Keys(mapper.imports)) {
		fmt.Fprintf(&header, "import %q;\n", path)
	}
	if len(mapper.imports) > 0 {
		header.WriteString("\n")
	}
	fmt.Fprintf(&header, protoGoPackage, config.GoPackage)
	return header.String() + buffer.String(), nil
}

func newTypeMapper(messages map[string]struct{},
	named map[string]string) *typeMapper {
	return &typeMapper{
		imports:  make(map[string]struct{}),
		messages: messages,
		named:    named,
		visiting: make(map[string]struct{}),
	}
}

// protoTypeOf returns the proto type for the Go type whose source is goType.
func (m *typeMapper) protoTypeOf(goType string) (string, error) {
	expr, err := parser.ParseExpr(goType)
	if err != nil {
		return "", fmt.Errorf("cannot map type %s to a proto type", goType)
	}
	return m.protoType(expr)
}

// protoType returns the proto type for the Go type expr.
func (m *typeMapper) protoType(expr ast.Expr) (string, error) {
	switch expr := expr.(type) {
	case *ast.Ident:
		return m.identProtoType(expr.Name)
	case *ast.SelectorExpr:
		if mapped, ok := wellKnownTypes[types.ExprString(expr)]; ok {
			if path, ok := protoImports[mapped]; ok {
				m.imports[path] = struct{}{}
			}
			return mapped, nil
		}
	case *ast.StarExpr:
		return m.protoType(expr.X)
	case *ast.ArrayType:
		return m.sliceProtoType(expr)
	case *ast.MapType:
		return m.mapProtoType(expr)
	}
	return "", fmt.Errorf("cannot map type %s to a proto type",
		types.ExprString(expr))
}

// basicProtoType returns the proto type for a predeclared Go type, or false if
// it has none. int and uint are 64 bits, their size on the platforms we build
// for.
func basicProtoType(name string) (string, bool) {
	typeName, ok := types.Universe.Lookup(name).(*types.TypeName)
	if !ok {
		return "", false
	}
	basic, ok := typeName.Type().(*types.Basic)
	if !ok {
		return "", false
	}
	switch basic.Kind() {
	case types.Bool:
		return "bool", true
	case types.String:
		return "string", true
	case types.Int8, types.Int16, types.Int32:
		return "int32", true
	case types.Int, types.Int64:
		return "int64", true
	case types.Uint8, types.Uint16, types.Uint32:
		return "uint32", true
	case types.Uint, types.Uint64:
		return "uint64", true
	case types.Float32:
		return "float", true
	case types.Float64:
		return "double", true
	}
	return "", false
}

// identProtoType returns the proto type for the type name, following a named
// type to its underlying type. A type which refers to itself is an error.
func (m *typeMapper) identProtoType(name string) (string, error) {
	if mapped, ok := basicProtoType(name); ok {
		return mapped, nil
	}
	if _, ok := m.messages[name]; ok {
		return name, nil
	}
	underlying, ok := m.named[name]
	if !ok {
		return "", fmt.Errorf("cannot map type %s to a proto type", name)
	}
	if _, ok := m.visiting[name]; ok {
		return "", fmt.Errorf("cannot map recursive type %s to a proto type",
			name)
	}
	m.visiting[name] = struct{}{}
	defer delete(m.visiting, name)
	mapped, err := m.protoTypeOf(underlying)
	if err != nil {
		return "", fmt.Errorf("type %s: %w", name, err)
	}
	return mapped, nil
}

// sliceProtoType returns bytes for []byte and []uint8 and repeated for any
// other slice. A named byte type is an integer, so a slice of it is repeated.
// Arrays and slices of collections are errors.
func (m *typeMapper) sliceProtoType(expr *ast.ArrayType) (string, error) {
	if expr.Len != nil {
		return "", fmt.Errorf("cannot map array type %s to a proto type",
			types.ExprString(expr))
	}
	if elem := types.ExprString(expr.Elt); elem == "byte" || elem == "uint8" {
		return "bytes", nil
	}
	elem, err := m.protoType(expr.Elt)
	if err != nil {
		return "", err
	}
	if isCollection(elem) {
		return "", fmt.Errorf("cannot map type %s to a proto type",
			types.ExprString(expr))
	}
	return "repeated " + elem, nil
}

// isCollection returns true for a repeated field or a map, which proto cannot
// nest.
func isCollection(typeName string) bool {
	return strings.HasPrefix(typeName, "repeated ") ||
		strings.HasPrefix(typeName, "map<")
}

// mapProtoType returns the proto type for the map type expr. The key must be a
// type which proto allows as a key.
func (m *typeMapper) mapProtoType(expr *ast.MapType) (string, error) {
	key, err := m.protoType(expr.Key)
	if err != nil {
		return "", err
	}
	value, err := m.protoType(expr.Value)
	if err != nil {
		return "", err
	}
	if !slices.Contains(protoKeyTypes, key) || isCollection(value) {
		return "", fmt.Errorf("cannot map type %s to a proto type",
			types.ExprString(expr))
	}
	return fmt.Sprintf("map<%s, %s>", key, value), nil
}
